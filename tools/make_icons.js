// Media Ctrl icons: SVG (same paths as the design mock) -> alpha-only LVGL 9 A8 images.
// Run from tools/:  npm install @resvg/resvg-js && node make_icons.js
// The firmware recolors each icon per state, so only coverage (alpha) is stored.
const { Resvg } = require('@resvg/resvg-js');
const fs = require('fs');
const path = require('path');

const S = 'stroke="#fff" fill="none" stroke-linecap="round" stroke-linejoin="round"';
const ICONS = {
  prev:    [26, `<path d="M6 5v14" ${S} stroke-width="2.4"/><path d="M19 5.5 9 12l10 6.5z" fill="#fff"/>`],
  next:    [26, `<path d="M18 5v14" ${S} stroke-width="2.4"/><path d="M5 5.5 15 12 5 18.5z" fill="#fff"/>`],
  play:    [34, `<path d="M8 4.8v14.4L19.5 12z" fill="#fff"/>`],
  pause:   [34, `<rect x="6" y="5" width="4.2" height="14" rx="1.2" fill="#fff"/><rect x="13.8" y="5" width="4.2" height="14" rx="1.2" fill="#fff"/>`],
  back15:  [22, `<path d="M5 12a7 7 0 1 0 2.1-5" ${S} stroke-width="2"/><path d="M5 3.5V8h4.5" ${S} stroke-width="2"/>`],
  fwd15:   [22, `<path d="M19 12a7 7 0 1 1-2.1-5" ${S} stroke-width="2"/><path d="M19 3.5V8h-4.5" ${S} stroke-width="2"/>`],
  shuffle: [22, `<path d="M3 7h3.5l9 10H20M3 17h3.5l2.8-3.1M14.7 10.1 17.5 7H20M17.5 4.5 20 7l-2.5 2.5M17.5 14.5 20 17l-2.5 2.5" ${S} stroke-width="2"/>`],
  repeat:  [22, `<path d="M4 11V9a3 3 0 0 1 3-3h12M16 3l3 3-3 3M20 13v2a3 3 0 0 1-3 3H5M8 21l-3-3 3-3" ${S} stroke-width="2"/>`],
  heart:   [22, `<path d="M12 20s-7.5-4.6-7.5-10.2A4.2 4.2 0 0 1 12 7.2a4.2 4.2 0 0 1 7.5 2.6C19.5 15.4 12 20 12 20z" ${S} stroke-width="2"/>`],
  mute:    [22, `<path d="M4 9.5v5h3.5l5 4v-13l-5 4z" ${S} stroke-width="2"/><path d="M16.5 9.5l5 5M21.5 9.5l-5 5" ${S} stroke-width="2"/>`],
  minus:   [18, `<path d="M5 12h14" ${S} stroke-width="2.6"/>`],
  plus:    [18, `<path d="M5 12h14M12 5v14" ${S} stroke-width="2.6"/>`],
  chevron: [12, `<path d="M15 5l-7 7 7 7" ${S} stroke-width="2.8"/>`],
};

const out = path.join(__dirname, '..', 'src', 'assets');
let all = '// Generated by tools/make_icons.js — do not edit.\n#include <lvgl.h>\n\n';
let hdr = '// Generated by tools/make_icons.js\n#pragma once\n#include <lvgl.h>\n';
for (const [name, [px, body]] of Object.entries(ICONS)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${body}</svg>`;
  const img = new Resvg(svg, { fitTo: { mode: 'width', value: px } }).render();
  const w = img.width, h = img.height, rgba = img.pixels;
  const a = [];
  for (let i = 0; i < w * h; i++) a.push(rgba[i * 4 + 3]);
  const rows = [];
  for (let y = 0; y < h; y++) rows.push('  ' + a.slice(y * w, y * w + w).map(v => '0x' + v.toString(16).padStart(2, '0')).join(','));
  all += `static const uint8_t ic_${name}_map[] = {\n${rows.join(',\n')}\n};\n`;
  all += `const lv_image_dsc_t ic_${name} = {\n  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = ${w}, .h = ${h}, .stride = ${w}, .reserved_2 = 0 },\n  .data_size = ${w * h},\n  .data = ic_${name}_map,\n  .reserved = NULL,\n};\n\n`;
  hdr += `LV_IMAGE_DECLARE(ic_${name});\n`;
}
fs.writeFileSync(path.join(out, 'icons.c'), all);
fs.writeFileSync(path.join(__dirname, '..', 'src', 'icons.h'), hdr);
console.log('wrote', Object.keys(ICONS).length, 'icons');
